"""Build standalone target-language launchers for valid Python scripts."""

from __future__ import annotations

from base64 import b64encode
import json
from pathlib import Path
from textwrap import wrap

from translation import Translation


TARGETS = frozenset({"javascript", "typescript", "ruby"})

BOOTSTRAP = """\
import importlib.machinery
import os
import sys
import types

with open(sys.argv[1], "rb") as embedded:
    source = embedded.read()
sys.argv = sys.argv[2:]
filename = sys.argv[0]
if not getattr(sys.flags, "safe_path", False):
    sys.path[0] = os.path.dirname(os.path.realpath(filename))
module = types.ModuleType("__main__")
module.__file__ = filename
module.__cached__ = None
module.__loader__ = importlib.machinery.SourceFileLoader("__main__", filename)
sys.modules["__main__"] = module
exec(compile(source, filename, "exec", dont_inherit=True), module.__dict__)
"""

NODE = """\
// Generated by Code Translator. This launcher runs the embedded script with Python.
const embedded = [
SOURCE
].join("");
const sourceName = Buffer.from(FILENAME, "base64").toString("utf8");
const startPython = BOOT;

async function main() {
    const { spawnSync } = await import("node:child_process");
    const fs = await import("node:fs");
    const os = await import("node:os");
    const path = await import("node:path");
    const filename = path.resolve(path.dirname(process.argv[1]), sourceName);
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), "code-translator-"));
    const sourceFile = path.join(directory, "embedded.py");
    try {
        fs.writeFileSync(sourceFile, Buffer.from(embedded, "base64"), { flag: "wx", mode: 0o600 });
        const python = process.env.CODE_TRANSLATOR_PYTHON ?? (process.platform === "win32" ? "python" : "python3");
        const child = spawnSync(python, ["-c", startPython, sourceFile, filename, ...process.argv.slice(2)], { stdio: "inherit" });
        if (child.error) throw child.error;
        if (child.signal) return child.signal;
        process.exitCode = child.status ?? 1;
    } finally {
        fs.rmSync(sourceFile, { force: true });
        fs.rmdirSync(directory);
    }
}

main().then(signal => {
    if (signal) process.kill(process.pid, signal);
}).catch(error => {
    console.error("Code Translator could not run Python: " + String(error));
    process.exitCode = 1;
});
"""

RUBY = """\
# Generated by Code Translator. This launcher runs the embedded script with Python.
require "base64"
require "tempfile"

embedded = [
SOURCE
].join
source_name = Base64.strict_decode64(FILENAME).force_encoding("UTF-8")
start_python = BOOT
status = nil
launched = nil
Tempfile.create(["code-translator-", ".py"]) do |file|
    file.binmode
    file.write(Base64.strict_decode64(embedded))
    file.close
    filename = File.expand_path(source_name, __dir__)
    python = ENV.fetch("CODE_TRANSLATOR_PYTHON") { RUBY_PLATFORM.match?(/mswin|mingw/) ? "python" : "python3" }
    launched = system(python, "-c", start_python, file.path, filename, *ARGV)
    status = $?
end
if launched.nil?
    warn "Code Translator could not run Python."
    exit 1
end
exit(128 + status.termsig) if status&.signaled?
exit(status&.exitstatus || 1)
"""


def render(source: Path, target: str, *, display_name: str | None = None,
           fallback_reason: str | None = None) -> Translation:
    filename = Path(display_name).name if display_name else source.name
    data = source.read_bytes()
    compile(data, filename, "exec", dont_inherit=True)
    chunks = wrap(b64encode(data).decode("ascii"), 96)
    source_lines = "\n".join(f'    "{chunk}",' for chunk in chunks)
    filename_literal = json.dumps(b64encode(filename.encode("utf-8")).decode("ascii"))
    template = RUBY if target == "ruby" else NODE
    code = template.replace("\nSOURCE\n", f"\n{source_lines}\n").replace("FILENAME", filename_literal)
    code = code.replace("BOOT", json.dumps(BOOTSTRAP))
    return Translation(code, fallback_reason, requires_python=True)
